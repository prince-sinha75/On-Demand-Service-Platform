/*
# Harden booking submission and references

This migration strengthens the existing booking request flow without removing or changing
any existing user data.

## 1. Modified table
- `bookings`
  - Adds `reference`, a short unique customer-facing booking reference.
  - Adds `request_key`, an optional idempotency key used to prevent accidental duplicate submissions.
  - Adds a unique index for a customer's non-null request keys.

## 2. Security and integrity
- The server-side create function now validates that requested times match the published hourly slots.
- Reusing the same request key for the same authenticated customer returns the original booking instead
  of creating a duplicate.
- Booking references are generated by PostgreSQL, not by the browser.

## 3. Important notes
1. Provider schedules are not configured yet, so bookings remain requests pending assignment.
2. No price, provider, or availability is fabricated by this change.
3. No destructive operations are performed.
*/

ALTER TABLE public.bookings
  ADD COLUMN IF NOT EXISTS reference text,
  ADD COLUMN IF NOT EXISTS request_key uuid;

UPDATE public.bookings
SET reference = 'HH-' || upper(substr(id::text, 1, 8))
WHERE reference IS NULL;

ALTER TABLE public.bookings
  ALTER COLUMN reference SET DEFAULT ('HH-' || upper(substr(gen_random_uuid()::text, 1, 8))),
  ALTER COLUMN reference SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS bookings_reference_key ON public.bookings (reference);
CREATE UNIQUE INDEX IF NOT EXISTS bookings_user_request_key ON public.bookings (user_id, request_key)
WHERE request_key IS NOT NULL;

CREATE OR REPLACE FUNCTION public.create_booking(
  p_service_id uuid,
  p_location text,
  p_scheduled_date date,
  p_start_time time,
  p_duration_hours integer,
  p_details jsonb DEFAULT '{}'::jsonb,
  p_request_key uuid DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_booking_id uuid;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF p_request_key IS NOT NULL THEN
    SELECT id INTO v_booking_id
    FROM public.bookings
    WHERE user_id = auth.uid() AND request_key = p_request_key;
    IF v_booking_id IS NOT NULL THEN
      RETURN v_booking_id;
    END IF;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.service_categories
    WHERE id = p_service_id AND active = true
  ) THEN
    RAISE EXCEPTION 'Service unavailable';
  END IF;

  IF p_scheduled_date < current_date THEN
    RAISE EXCEPTION 'Booking date must be today or later';
  END IF;

  IF p_start_time < time '08:00' OR p_start_time > time '19:00' OR extract(minute FROM p_start_time) <> 0 THEN
    RAISE EXCEPTION 'Invalid start time';
  END IF;

  IF p_duration_hours IS NULL OR p_duration_hours < 1 OR p_duration_hours > 24 THEN
    RAISE EXCEPTION 'Invalid duration';
  END IF;

  IF p_location IS NULL OR char_length(btrim(p_location)) < 3 OR char_length(p_location) > 500 THEN
    RAISE EXCEPTION 'Invalid location';
  END IF;

  IF p_details IS NULL OR jsonb_typeof(p_details) <> 'object' THEN
    RAISE EXCEPTION 'Invalid booking details';
  END IF;

  INSERT INTO public.bookings (
    user_id, service_id, location, scheduled_date, start_time, duration_hours, details, request_key
  ) VALUES (
    auth.uid(), p_service_id, btrim(p_location), p_scheduled_date, p_start_time, p_duration_hours, p_details, p_request_key
  )
  RETURNING id INTO v_booking_id;

  RETURN v_booking_id;
EXCEPTION
  WHEN unique_violation THEN
    SELECT id INTO v_booking_id
    FROM public.bookings
    WHERE user_id = auth.uid() AND request_key = p_request_key;
    IF v_booking_id IS NOT NULL THEN
      RETURN v_booking_id;
    END IF;
    RAISE;
END;
$$;

REVOKE ALL ON FUNCTION public.create_booking(uuid, text, date, time, integer, jsonb) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.create_booking(uuid, text, date, time, integer, jsonb, uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_booking(uuid, text, date, time, integer, jsonb, uuid) TO authenticated;
